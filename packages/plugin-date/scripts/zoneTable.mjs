// Writes src/zoneTable.ts from the IANA tz database's zone.tab (country, coordinates, zone):
// the data guessZone uses. Run it when the tz database changes:
//   node scripts/zoneTable.mjs [/usr/share/zoneinfo/zone.tab]
import { readFileSync, writeFileSync } from 'node:fs';

const source = process.argv[2] ?? '/usr/share/zoneinfo/zone.tab';
const toDegrees = (sign, digits) => {
  const d = digits.length <= 5 ? digits.slice(0, -2) : digits.slice(0, -4);
  const m = Number(digits.length <= 5 ? digits.slice(-2) : digits.slice(-4, -2));
  const s = digits.length <= 5 ? 0 : Number(digits.slice(-2));
  const value = Number(d) + m / 60 + s / 3600;
  return Math.round((sign === '-' ? -value : value) * 100) / 100;
};
const rows = readFileSync(source, 'utf8')
  .split('\n')
  .filter((line) => line && !line.startsWith('#'))
  .map((line) => {
    const [country, coords, zone] = line.split('\t');
    const [, latSign, lat, lonSign, lon] = coords.match(/^([+-])(\d+)([+-])(\d+)$/);
    return `${country} ${toDegrees(latSign, lat)} ${toDegrees(lonSign, lon)} ${zone}`;
  });
writeFileSync(
  new URL('../src/zoneTable.ts', import.meta.url),
  `/**
 * Time zones with their country (ISO 3166) and main city's coordinates, from the IANA tz
 * database's zone.tab: "CC lat lon Zone" per line. Generated by scripts/zoneTable.mjs; don't edit.
 */
export const ZONE_TABLE = \`${rows.join('\n')}\`;
`
);
console.log(`${rows.length} zones`);
